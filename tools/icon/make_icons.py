#!/usr/bin/env python3
"""Generate every app icon from one drawing.

The motif (a screen showing an EQ response curve over six level-meter bars,
one per output of the DSP 206) is defined once, in a 100 x 100 space, and
written as:

- data/icons/hicolor/scalable/apps/org.meredsp206.Editor.svg  (Linux, GNOME style)
- android/app/src/main/res/drawable/ic_launcher_{background,foreground,monochrome}.xml
  (Android adaptive icon, 108 x 108 dp layers)
- android/store/icon-512.svg  (Google Play icon source; --png renders icon-512.png)

Run from anywhere: python3 -I tools/icon/make_icons.py [--png]
tools/tests/test_icons.py checks that the committed files match this script.
Original artwork: no vendor names, logos or artwork.
"""
import pathlib
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
APP_ID = "org.meredsp206.Editor"

# Palette.
BG_TOP = "#3A5280"
BG_BOTTOM = "#141D30"
SCREEN = "#0B1628"
SCREEN_EDGE = "#3A5A85"
GRID = "#1C3150"
CURVE = "#6FD6FF"
GLOW = "#49C6FF"
BAR_TOP = "#57E389"
BAR_BOTTOM = "#26A269"
BAR_CAP = "#F6D32D"
HANDLE = "#FFFFFF"

# ---- the motif, in a 100 x 100 space (content spans x 6..94, y 10..94) ----

CENTER = (50.0, 52.0)  # centre of the content box


def rounded_rect(x, y, w, h, r):
    """Path data of a rounded rectangle (valid in SVG and Android VectorDrawable)."""
    r = min(r, w / 2, h / 2)
    return (
        f"M{x + r:g},{y:g} h{w - 2 * r:g} a{r:g},{r:g} 0 0 1 {r:g},{r:g} "
        f"v{h - 2 * r:g} a{r:g},{r:g} 0 0 1 {-r:g},{r:g} h{-(w - 2 * r):g} "
        f"a{r:g},{r:g} 0 0 1 {-r:g},{-r:g} v{-(h - 2 * r):g} a{r:g},{r:g} 0 0 1 {r:g},{-r:g} z"
    )


SCREEN_PATH = rounded_rect(6, 10, 88, 58, 9)
GRID_PATH = "M28,15 V64 M50,15 V64 M72,15 V64 M11,39 H89"
# Low shelf, a dip, a peak and a high cut: a typical loudspeaker EQ.
CURVE_PATH = "M11,35 C19,35 24,35 29,40 C33,44 35,48 40,48 C47,48 52,23 63,23 C72,23 79,44 89,61"
AREA_PATH = CURVE_PATH + " L89,67 L11,67 Z"
HANDLE_CENTER = (63, 23)

# Six output meters: (height, has an amber cap).
BARS = [(12, False), (17, True), (10, False), (20, True), (15, False), (8, False)]
BAR_W, BAR_GAP, BAR_BOTTOM_Y, BAR_X0 = 10.0, 5.6, 94.0, 6.0


def bar_paths():
    """(cap, body) path data for each bar; cap is None without an amber top."""
    out = []
    for i, (h, cap) in enumerate(BARS):
        x = BAR_X0 + i * (BAR_W + BAR_GAP)
        top = BAR_BOTTOM_Y - h
        cap_path = rounded_rect(x, top, BAR_W, 5, 2) if cap else None
        body_top = top + 3 if cap else top
        out.append((cap_path, rounded_rect(x, body_top, BAR_W, BAR_BOTTOM_Y - body_top, 2)))
    return out


def circle_path(cx, cy, r):
    return f"M{cx - r:g},{cy:g} a{r:g},{r:g} 0 1 0 {2 * r:g},0 a{r:g},{r:g} 0 1 0 {-2 * r:g},0 z"


def transform_for(scale, cx, cy):
    """Translation that puts the motif's content centre at (cx, cy)."""
    return cx - CENTER[0] * scale, cy - CENTER[1] * scale


# ---- SVG ------------------------------------------------------------------


def svg_motif(indent="    "):
    lines = [
        f'<path d="{SCREEN_PATH}" fill="{SCREEN}" stroke="{SCREEN_EDGE}" stroke-width="1.5"/>',
        f'<path d="{GRID_PATH}" fill="none" stroke="{GRID}" stroke-width="1"/>',
        f'<path d="{AREA_PATH}" fill="url(#area)"/>',
        f'<path d="{CURVE_PATH}" fill="none" stroke="{GLOW}" stroke-opacity="0.25" '
        'stroke-width="9" stroke-linecap="round" stroke-linejoin="round"/>',
        f'<path d="{CURVE_PATH}" fill="none" stroke="{CURVE}" stroke-width="4" '
        'stroke-linecap="round" stroke-linejoin="round"/>',
        f'<path d="{circle_path(*HANDLE_CENTER, 4.2)}" fill="{HANDLE}" stroke="{GLOW}" stroke-width="1.6"/>',
    ]
    for cap, body in bar_paths():
        if cap:
            lines.append(f'<path d="{cap}" fill="{BAR_CAP}"/>')
        lines.append(f'<path d="{body}" fill="url(#bar)"/>')
    return "\n".join(indent + line for line in lines)


SVG_DEFS = f"""  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="{BG_TOP}"/>
      <stop offset="1" stop-color="{BG_BOTTOM}"/>
    </linearGradient>
    <linearGradient id="area" gradientUnits="userSpaceOnUse" x1="0" y1="23" x2="0" y2="67">
      <stop offset="0" stop-color="{GLOW}" stop-opacity="0.45"/>
      <stop offset="1" stop-color="{GLOW}" stop-opacity="0"/>
    </linearGradient>
    <linearGradient id="bar" gradientUnits="userSpaceOnUse" x1="0" y1="74" x2="0" y2="94">
      <stop offset="0" stop-color="{BAR_TOP}"/>
      <stop offset="1" stop-color="{BAR_BOTTOM}"/>
    </linearGradient>
  </defs>"""


def linux_svg():
    """GNOME-style app icon: a rounded device body with depth, 128 x 128."""
    tx, ty = transform_for(0.9, 64, 63)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/icon/make_icons.py: edit the script, not this file. -->
<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128">
{SVG_DEFS}
  <path d="{rounded_rect(10, 16, 108, 102, 18)}" fill="#0D1320"/>
  <path d="{rounded_rect(10, 12, 108, 102, 18)}" fill="url(#bg)"/>
  <path d="{rounded_rect(10.5, 12.5, 107, 101, 17.5)}" fill="none" stroke="#FFFFFF" stroke-opacity="0.12"/>
  <g transform="translate({tx:g},{ty:g}) scale(0.9)">
{svg_motif()}
  </g>
</svg>
"""


#: Motif scale on the 108 dp adaptive icon: the content stays inside the
#: 66 dp safe circle that every launcher mask keeps.
ANDROID_SCALE = 0.56


def store_svg():
    """Google Play icon, 512 x 512, full square (Play applies its own mask).
    It shows the adaptive icon's visible 72 dp area."""
    scale = ANDROID_SCALE * 512 / 72
    tx, ty = transform_for(scale, 256, 256)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/icon/make_icons.py: edit the script, not this file. -->
<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">
{SVG_DEFS}
  <rect width="512" height="512" fill="url(#bg)"/>
  <g transform="translate({tx:g},{ty:g}) scale({scale:g})">
{svg_motif()}
  </g>
</svg>
"""


# ---- Android VectorDrawable ---------------------------------------------------


def argb(color, alpha=1.0):
    return f"#{round(alpha * 255):02X}{color.lstrip('#').upper()}"


VD_HEAD = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/icon/make_icons.py: edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"{extra}
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
"""


def android_background():
    return (
        VD_HEAD.format(extra='\n    xmlns:aapt="http://schemas.android.com/aapt"')
        + f"""    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="0"
                android:startY="0"
                android:endX="108"
                android:endY="108"
                android:startColor="{argb(BG_TOP)}"
                android:endColor="{argb(BG_BOTTOM)}" />
        </aapt:attr>
    </path>
</vector>
"""
    )


def vd_group(body):
    tx, ty = transform_for(ANDROID_SCALE, 54, 54)
    return (
        f'    <group\n        android:translateX="{tx:g}"\n        android:translateY="{ty:g}"\n'
        f'        android:scaleX="{ANDROID_SCALE:g}"\n        android:scaleY="{ANDROID_SCALE:g}">\n'
        + body
        + "    </group>\n</vector>\n"
    )


def vd_path(data, **attrs):
    lines = [f'        <path android:pathData="{data}"']
    lines += [f'            android:{k}="{v}"' for k, v in attrs.items()]
    return "\n".join(lines) + " />\n"


STROKE = {"strokeLineCap": "round", "strokeLineJoin": "round"}


def android_foreground():
    body = vd_path(SCREEN_PATH, fillColor=argb(SCREEN), strokeColor=argb(SCREEN_EDGE), strokeWidth="1.5")
    body += vd_path(GRID_PATH, strokeColor=argb(GRID), strokeWidth="1")
    body += vd_path(AREA_PATH, fillColor=argb(GLOW, 0.22))
    body += vd_path(CURVE_PATH, strokeColor=argb(GLOW, 0.25), strokeWidth="9", **STROKE)
    body += vd_path(CURVE_PATH, strokeColor=argb(CURVE), strokeWidth="4", **STROKE)
    body += vd_path(circle_path(*HANDLE_CENTER, 4.2), fillColor=argb(HANDLE), strokeColor=argb(GLOW), strokeWidth="1.6")
    for cap, bar in bar_paths():
        if cap:
            body += vd_path(cap, fillColor=argb(BAR_CAP))
        body += vd_path(bar, fillColor=argb(BAR_TOP))
    return VD_HEAD.format(extra="") + vd_group(body)


def android_monochrome():
    """Themed-icon layer (Android 13+): shapes only, the launcher tints them."""
    ink = "#FF000000"
    body = vd_path(SCREEN_PATH, strokeColor=ink, strokeWidth="3")
    body += vd_path(CURVE_PATH, strokeColor=ink, strokeWidth="5", **STROKE)
    body += vd_path(circle_path(*HANDLE_CENTER, 4.6), fillColor=ink)
    for _, bar in bar_paths():
        body += vd_path(bar, fillColor=ink)
    return VD_HEAD.format(extra="") + vd_group(body)


# ---- output -------------------------------------------------------------------------

DRAWABLE = "android/app/src/main/res/drawable"


ADAPTIVE_ICON = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/icon/make_icons.py: edit the script, not this file.
     In mipmap-anydpi-v26 because aapt2 moves an adaptive icon with
     <monochrome> (API 33) out of a plain mipmap-anydpi folder. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""


def build():
    """Every generated file: repository path -> content."""
    mipmap = "android/app/src/main/res/mipmap-anydpi-v26"
    return {
        f"{mipmap}/ic_launcher.xml": ADAPTIVE_ICON,
        f"{mipmap}/ic_launcher_round.xml": ADAPTIVE_ICON,
        f"data/icons/hicolor/scalable/apps/{APP_ID}.svg": linux_svg(),
        f"{DRAWABLE}/ic_launcher_background.xml": android_background(),
        f"{DRAWABLE}/ic_launcher_foreground.xml": android_foreground(),
        f"{DRAWABLE}/ic_launcher_monochrome.xml": android_monochrome(),
        "android/store/icon-512.svg": store_svg(),
    }


def chromium():
    for candidate in [shutil.which("chromium"), shutil.which("chromium-browser")]:
        if candidate:
            return candidate
    found = sorted(pathlib.Path("/opt/pw-browsers").glob("chromium-*/chrome-linux64/chrome"))
    return str(found[-1]) if found else None


def render_png(svg_path, png_path, size):
    """Rasterise an SVG with headless Chromium (as design/render.sh does)."""
    browser = chromium()
    if browser is None:
        sys.exit("no Chromium found: install it or set PATH")
    with tempfile.TemporaryDirectory() as tmp:
        page = pathlib.Path(tmp) / "icon.html"
        page.write_text(
            f'<html><body style="margin:0"><img src="file://{svg_path}" '
            f'width="{size}" height="{size}" style="display:block"></body></html>'
        )
        subprocess.run(
            [browser, "--headless=new", "--no-sandbox", "--disable-gpu", "--hide-scrollbars",
             "--force-device-scale-factor=1", f"--window-size={size},{size}",
             "--default-background-color=00000000", f"--screenshot={png_path}", page.as_uri()],
            check=True, capture_output=True,
        )


def main(argv):
    for rel, text in build().items():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print("wrote", rel)
    if "--png" in argv:
        render_png(ROOT / "android/store/icon-512.svg", ROOT / "android/store/icon-512.png", 512)
        print("rendered android/store/icon-512.png")


if __name__ == "__main__":
    main(sys.argv[1:])
